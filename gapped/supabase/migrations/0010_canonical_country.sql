-- ─────────────────────────────────────────────────────────────────────────────
-- Canonical country codes.
--
-- board_top filters leaderboard entries with `e.country = p_country`. Two codes
-- meaning one country therefore split a nation across two half-populated
-- boards. Nothing errors and nothing in the app can show which board is real.
--
-- Sixteen codes can do this. `UK` is the important one and it is neither a typo
-- nor a withdrawn code: it is *exceptionally reserved* in ISO 3166-1, CLDR maps
-- it onto the same country as `GB`, and any locale API can produce it. The rest
-- are formerly-used codes with live successors (SU→RU, YU→RS, ZR→CD, DD→DE, …).
--
-- The client canonicalises on every write path (src/data/countries.ts). This
-- migration makes the bad state unrepresentable rather than merely unwritten,
-- so a direct SQL write or a future second client cannot reintroduce it.
--
-- NO-OP SAFE AND IDEMPOTENT. Both environments currently hold only `GB` and
-- nulls, so the canonicalisation pass is expected to report 0 rows changed on
-- its first run. That is the point: a migration that has never run is untested
-- code, and one that reports what it did can be re-run to prove it is stable.
-- Every statement below is guarded, so running this file twice is safe and the
-- second run reports zeroes.
-- ─────────────────────────────────────────────────────────────────────────────

-- ── the canonical set ────────────────────────────────────────────────────────
-- 249 assigned ISO 3166-1 alpha-2 codes plus XK. Generated by
-- scripts/generate-countries.mjs from the CLDR data in Node's ICU; the same
-- 250 rows the picker offers. See src/data/countries.provenance.json for the
-- ICU/CLDR version this was cut from, and the generator for why XK is in and
-- why the reserved codes (AC, TA, EA, IC, CQ, …) are out.

