-- ── canonicalisation pass ────────────────────────────────────────────────────

do $$
declare
  n_profiles int;
  n_entries  int;
  n_payloads int;
begin
  create temp table _alias (from_code char(2) primary key, to_code char(2) not null);
  insert into _alias (from_code, to_code) values
    ('AN', 'CW'),
    ('BU', 'MM'),
    ('CS', 'RS'),
    ('DD', 'DE'),
    ('DY', 'BJ'),
    ('FX', 'FR'),
    ('HV', 'BF'),
    ('NH', 'VU'),
    ('RH', 'ZW'),
    ('SU', 'RU'),
    ('TP', 'TL'),
    ('UK', 'GB'),
    ('VD', 'VN'),
    ('YD', 'YE'),
    ('YU', 'RS'),
    ('ZR', 'CD');

  with u as (
    update profiles p set country = a.to_code
      from _alias a where p.country = a.from_code
      returning 1
  ) select count(*) into n_profiles from u;

  -- Denormalised on purpose: an entry records the country the run was set in,
  -- and must not move when the driver later emigrates. Canonicalising it is a
  -- spelling change, not a re-derivation.
  with u as (
    update leaderboard_entries e set country = a.to_code
      from _alias a where e.country = a.from_code
      returning 1
  ) select count(*) into n_entries from u;

  -- ── achievements.payload->>'country' ──────────────────────────────────────
  -- IN PLACE, and the distinction matters.
  --
  -- This rewrites ZR to CD: the same country, spelled canonically. It does NOT
  -- re-read profiles.country, and must never be changed to.
  --
  -- The payload is written once — grantAchievements upserts with
  -- ignoreDuplicates, so the row is never updated after the first grant — which
  -- makes it a permanent snapshot of where the driver was when they topped that
  -- board, not a cache of where they are now. leaderboard_entries.country is a
  -- snapshot too, so an emigrant's old entries stay put and they may genuinely
  -- still hold that board. Re-deriving from profiles would relabel the badge
  -- "Top of the FR board" for a run set in GB: a badge that lies.
  --
  -- There is deliberately no constraint on this field. It is not an independent
  -- input — achievements grants `insert`/`update`/`delete` to no client role
  -- (RLS on, select-only policy), so the sole writer is verify-drive under the
  -- service role, and it copies the value straight out of profiles.country,
  -- which the foreign key below constrains. The payload inherits that
  -- constraint transitively. Two tests pin the single-writer property, which is
  -- the assumption that argument rests on.
  with u as (
    update achievements ach
      set payload = jsonb_set(ach.payload, '{country}', to_jsonb(a.to_code::text))
      from _alias a where ach.payload->>'country' = a.from_code
      returning 1
  ) select count(*) into n_payloads from u;

  drop table _alias;

  raise notice 'country canonicalisation: profiles=% leaderboard_entries=% achievements.payload=%',
    n_profiles, n_entries, n_payloads;
end $$;

-- ── make the bad state unrepresentable ───────────────────────────────────────
-- Foreign keys rather than CHECK constraints: the valid set is data, so it
-- lives in a table that can be extended by a migration instead of in a
-- constraint body that has to be dropped and rebuilt. Both columns are
-- nullable and stay nullable — "no country set" is a state the app handles
-- everywhere, and is the right answer for a driver who has not chosen one.

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'profiles_country_fkey') then
    alter table profiles
      add constraint profiles_country_fkey foreign key (country) references countries (code);
  end if;

  if not exists (select 1 from pg_constraint where conname = 'leaderboard_entries_country_fkey') then
    alter table leaderboard_entries
      add constraint leaderboard_entries_country_fkey foreign key (country) references countries (code);
  end if;
end $$;
